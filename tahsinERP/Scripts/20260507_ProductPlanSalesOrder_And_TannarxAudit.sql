use [DBTHSN-IPACK]
IF COL_LENGTH('dbo.PRODUCTPLANs', 'SalesOrderID') IS NULL
BEGIN
    ALTER TABLE dbo.PRODUCTPLANs
    ADD SalesOrderID INT NULL;
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.foreign_keys
    WHERE name = 'FK_PRODUCTPLAN_S_ORDERS'
)
BEGIN
    ALTER TABLE dbo.PRODUCTPLANs
    ADD CONSTRAINT FK_PRODUCTPLAN_S_ORDERS
        FOREIGN KEY (SalesOrderID) REFERENCES dbo.S_ORDERS(ID);
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_PRODUCTPLAN_SalesOrderID'
      AND object_id = OBJECT_ID('dbo.PRODUCTPLAN')
)
BEGIN
    CREATE INDEX IX_PRODUCTPLAN_SalesOrderID
        ON dbo.PRODUCTPLANs(SalesOrderID);
END;

IF OBJECT_ID('dbo.TANNARX_ACTUAL_AUDIT', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TANNARX_ACTUAL_AUDIT
    (
        ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        TannarxID INT NOT NULL,
        SelectedPath NVARCHAR(20) NULL,
        MethodCode NVARCHAR(64) NULL,
        ConfidenceScore NVARCHAR(16) NULL,
        CoveragePercent DECIMAL(18,6) NOT NULL CONSTRAINT DF_TANNARX_AUDIT_Coverage DEFAULT (0),
        ReconcileDelta DECIMAL(18,6) NOT NULL CONSTRAINT DF_TANNARX_AUDIT_Reconcile DEFAULT (0),
        SourceAmount DECIMAL(18,6) NOT NULL CONSTRAINT DF_TANNARX_AUDIT_SourceAmount DEFAULT (0),
        DenominatorQty DECIMAL(18,6) NOT NULL CONSTRAINT DF_TANNARX_AUDIT_DenQty DEFAULT (0),
        ReasonCode NVARCHAR(64) NULL,
        UpdatedAt DATETIME NOT NULL CONSTRAINT DF_TANNARX_AUDIT_UpdatedAt DEFAULT (GETDATE()),
        CONSTRAINT UQ_TANNARX_ACTUAL_AUDIT_TannarxID UNIQUE (TannarxID),
        CONSTRAINT FK_TANNARX_ACTUAL_AUDIT_TANNARX FOREIGN KEY (TannarxID) REFERENCES dbo.TANNARX(ID)
    );
END;
